"""Build the fine-tuning set for Ithaca's on-device model.

Sources (all permissively licensed — see model/README.md):
  1. Teacher data generated by generate_teacher_data.py (if present):
     Ithaca-specific tool use and answers from an open-weight teacher.
  2. NousResearch/hermes-function-calling-v1 (Apache-2.0): general
     function-calling conversations in Hermes format.
  3. HuggingFaceTB/smoltalk "everyday-conversations": short chit-chat so the
     model keeps a natural conversational register.

Output: model/data/{train,valid}.jsonl in mlx-lm's chat/tools format:
  {"messages": [...], "tools": [...]}   (tools optional)
"""

from __future__ import annotations

import argparse
import json
import random
import re
from pathlib import Path

from datasets import load_dataset

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data"

TOOL_CALL_RE = re.compile(r"<tool_call>\s*(.*?)\s*</tool_call>", re.S)
TOOLS_RE = re.compile(r"<tools>\s*(.*?)\s*</tools>", re.S)
RESPONSE_RE = re.compile(r"<tool_response>\s*(.*?)\s*</tool_response>", re.S)


def _loads_loose(text: str):
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        try:
            import ast

            return ast.literal_eval(text)
        except (ValueError, SyntaxError):
            return None


def convert_hermes(row: dict) -> dict | None:
    """Hermes `conversations` → OpenAI-style messages with structured tool calls."""
    conv = row.get("conversations") or []
    tools: list = []
    column = row.get("tools")
    if isinstance(column, str) and column.strip():
        parsed = _loads_loose(column)
        if isinstance(parsed, list):
            tools = [t if "type" in t else {"type": "function", "function": t} for t in parsed if isinstance(t, dict)]
    messages: list[dict] = []
    for turn in conv:
        role, value = turn.get("from"), turn.get("value", "")
        if role == "system":
            # The prose mentions "<tools> </tools>" before the real block; take the longest.
            blocks = sorted(TOOLS_RE.findall(value), key=len)
            m = re.search(re.escape(blocks[-1]), value) if blocks and not tools else None
            if m and m.group(0).strip():
                parsed = _loads_loose(m.group(0))
                if isinstance(parsed, list):
                    tools = [t if "type" in t else {"type": "function", "function": t} for t in parsed if isinstance(t, dict)]
                elif isinstance(parsed, dict):
                    tools = [parsed if "type" in parsed else {"type": "function", "function": parsed}]
                else:
                    # Some rows list tools as consecutive JSON objects.
                    objs = [_loads_loose(x) for x in re.findall(r"\{.*?\}(?=\s*\{|\s*$)", m.group(0), re.S)]
                    tools = [o if "type" in o else {"type": "function", "function": o} for o in objs if isinstance(o, dict)]
            # The chat template renders tools itself; drop Hermes' own system prompt.
        elif role == "human":
            messages.append({"role": "user", "content": value})
        elif role == "gpt":
            calls = []
            for raw in TOOL_CALL_RE.findall(value):
                obj = _loads_loose(raw)
                if isinstance(obj, dict) and obj.get("name"):
                    calls.append({"type": "function", "function": {"name": obj["name"], "arguments": obj.get("arguments", {})}})
            text = TOOL_CALL_RE.sub("", value).strip()
            msg: dict = {"role": "assistant", "content": text}
            if calls:
                msg["tool_calls"] = calls
            messages.append(msg)
        elif role == "tool":
            for raw in RESPONSE_RE.findall(value) or [value]:
                messages.append({"role": "tool", "content": raw.strip()})
    if not tools or not any(m.get("tool_calls") for m in messages) or messages[-1]["role"] != "assistant":
        return None
    return {"messages": messages, "tools": tools}


CLOSERS = re.compile(r"\b(thanks|thank you|bye|goodbye|that's all|great, thanks|perfect|awesome)\b", re.I)


def cut_conversation(messages: list[dict]) -> dict | None:
    """End a chat on a substantive answer.

    mlx-lm's --mask-prompt trains only on the final assistant message, and
    everyday-conversation threads usually end with "You're welcome!" — training
    on those collapses a small model into pleasantries. Cut at a random
    assistant turn whose user message is a real request.
    """
    msgs = [m for m in messages if m["role"] in ("user", "assistant", "system")]
    good = [
        i for i, m in enumerate(msgs)
        if m["role"] == "assistant" and i > 0 and msgs[i - 1]["role"] == "user"
        and len(msgs[i - 1]["content"]) > 25 and not CLOSERS.search(msgs[i - 1]["content"])
        and len(m["content"]) > 60
    ]
    if not good:
        return None
    end = random.choice(good)
    return {"messages": msgs[: end + 1]}


def load_teacher(path: Path) -> list[dict]:
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--hermes", type=int, default=1200, help="Hermes function-calling examples to include")
    ap.add_argument("--chat", type=int, default=400, help="Everyday-conversation examples to include")
    ap.add_argument("--teacher", type=Path, default=OUT / "teacher.jsonl")
    ap.add_argument("--valid-frac", type=float, default=0.05)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    random.seed(args.seed)
    OUT.mkdir(parents=True, exist_ok=True)

    examples: list[dict] = []

    teacher = load_teacher(args.teacher)
    print(f"teacher examples: {len(teacher)}")
    # Ithaca-specific data matters most; upweight it.
    examples += teacher * 2

    if args.hermes:
        ds = load_dataset("NousResearch/hermes-function-calling-v1", data_files="func-calling-singleturn.json", split="train")
        converted = [c for c in (convert_hermes(r) for r in ds) if c]
        random.shuffle(converted)
        print(f"hermes function-calling: {len(converted)} usable, taking {min(args.hermes, len(converted))}")
        examples += converted[: args.hermes]

    if args.chat:
        try:
            ds = load_dataset("HuggingFaceTB/smoltalk", "everyday-conversations", split="train")
            rows = [c for c in (cut_conversation(r["messages"]) for r in ds) if c]
            random.shuffle(rows)
            print(f"everyday conversations: taking {min(args.chat, len(rows))}")
            examples += rows[: args.chat]
        except Exception as exc:  # noqa: BLE001 - optional source
            print(f"skipping smoltalk: {exc}")

    if not examples:
        raise SystemExit("No training data. Generate teacher data or enable the public datasets.")

    random.shuffle(examples)
    n_valid = max(8, int(len(examples) * args.valid_frac))
    valid, train = examples[:n_valid], examples[n_valid:]
    for name, rows in (("train", train), ("valid", valid)):
        with open(OUT / f"{name}.jsonl", "w", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"wrote {len(train)} train / {len(valid)} valid → {OUT}")


if __name__ == "__main__":
    main()
